"use client";
import { useRef, useState } from "react";
import Link from "next/link";
import { Check, Trash2, Upload } from "lucide-react";
import { Page, PageHeader } from "@/components/shell/app-shell";
import { Button } from "@/components/ui/button";
import { Badge } from "@/components/ui/badge";
import { api } from "@/lib/api";
import { useData } from "@/lib/use-data";
import { useStudio } from "@/lib/client-store";
import type { Asset } from "@/lib/types";
import { cn, timeAgo } from "@/lib/utils";

const SOURCE = { "art-director": "Art Director", imported: "Imported", seed: "Studio original" };
const src = (a: Asset) => (a.kind === "svg" ? `data:image/svg+xml;utf8,${encodeURIComponent(a.data)}` : a.data);

export default function AssetsPage() {
  const toast = useStudio((s) => s.toast);
  const { data, refresh } = useData<{ assets: Asset[] }>("/api/assets");
  const [filter, setFilter] = useState<"all" | Asset["source"]>("all");
  const file = useRef<HTMLInputElement>(null);
  const assets = (data?.assets ?? []).filter((a) => filter === "all" || a.source === filter);

  async function upload(f: File) {
    if (f.size > 2_000_000) return toast({ title: "That file is over 2 MB", tone: "error" });
    const data = f.type === "image/svg+xml" ? await f.text() : await new Promise<string>((res) => {
      const r = new FileReader();
      r.onload = () => res(String(r.result));
      r.readAsDataURL(f);
    });
    try {
      await api("/api/assets", { method: "POST", json: { name: f.name.replace(/\.[^.]+$/, ""), mime: f.type, data } });
      toast({ title: "Asset imported", body: "Marked as approved for use." });
      await refresh();
    } catch (e) {
      toast({ title: "Import failed", body: (e as Error).message, tone: "error" });
    }
  }

  return (
    <Page>
      <PageHeader
        eyebrow="Assets"
        title="Asset library"
        description="SVG motifs drawn by the Art Director, studio originals, and approved assets you import. No image-generation model is connected; nothing here was generated by one."
        actions={
          <>
            <input ref={file} type="file" accept="image/svg+xml,image/png,image/jpeg,image/webp" className="hidden" onChange={(e) => e.target.files?.[0] && void upload(e.target.files[0])} />
            <Button onClick={() => file.current?.click()}><Upload /> Import approved asset</Button>
          </>
        }
      />
      <div className="mb-6 flex flex-wrap gap-1 rounded-full bg-ivory-deep p-1 sm:inline-flex">
        {(["all", "art-director", "seed", "imported"] as const).map((f) => (
          <button key={f} onClick={() => setFilter(f)} aria-pressed={filter === f} className={cn("rounded-full px-3.5 py-1.5 text-[13px]", filter === f ? "bg-paper text-midnight shadow-soft" : "text-ink/60")}>{f === "all" ? "All" : SOURCE[f]}</button>
        ))}
      </div>
      <div className="grid grid-cols-2 gap-4 sm:grid-cols-3 lg:grid-cols-5">
        {assets.map((a) => (
          <div key={a.id} className="group overflow-hidden rounded-3xl border border-line/70 bg-paper">
            <div className="grid aspect-square place-items-center bg-[conic-gradient(at_50%_50%,#efe8dc_25%,#f7f3ec_0_50%,#efe8dc_0_75%,#f7f3ec_0)] bg-[length:16px_16px] p-6">
              <img src={src(a)} alt={a.name} className="max-h-full max-w-full" />
            </div>
            <div className="p-3">
              <p className="truncate text-[13px] font-medium text-midnight">{a.name}</p>
              <div className="mt-1.5 flex items-center justify-between">
                <Badge tone={a.approved ? "sage" : "neutral"}>{a.approved ? "Approved" : SOURCE[a.source]}</Badge>
                <span className="flex opacity-0 transition group-hover:opacity-100 focus-within:opacity-100">
                  {!a.approved && <Button size="icon-sm" variant="ghost" aria-label="Approve" onClick={async () => (await api(`/api/assets/${a.id}`, { method: "PATCH", json: { approved: true } }), refresh())}><Check /></Button>}
                  <Button size="icon-sm" variant="ghost" aria-label="Delete" onClick={async () => (await api(`/api/assets/${a.id}`, { method: "DELETE" }), refresh())}><Trash2 /></Button>
                </span>
              </div>
              <p className="mt-1 text-[11px] text-muted">{a.gameId ? <Link className="hover:underline" href={`/games/${a.gameId}`}>From a game</Link> : "Library"} · {timeAgo(a.createdAt)}</p>
            </div>
          </div>
        ))}
      </div>
      {data && !assets.length && <p className="rounded-3xl border border-dashed border-line p-12 text-center text-[14px] text-muted">No assets here yet.</p>}
    </Page>
  );
}
