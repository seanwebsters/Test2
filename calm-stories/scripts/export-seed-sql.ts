/**
 * Writes supabase/seed.sql from the same seed used by the local store, so a
 * Supabase project starts with the identical prototype catalogue.
 *   npm run db:seed-sql
 */
import fs from "node:fs";
import path from "node:path";
import { buildSeedSnapshot } from "../src/lib/seed/build";
import type { TableName } from "../src/lib/db/types";

// Foreign-key-safe insert order.
const ORDER: TableName[] = [
  "users", "user_roles", "subscription_entitlements", "creator_profiles", "soundscapes", "series", "seasons",
  "audio_assets", "episodes", "publishing_schedules", "editorial_reviews", "content_reports", "user_libraries",
  "series_follows", "creator_follows", "listening_progress", "listening_events", "notifications", "user_settings",
  "production_workflows", "agent_settings", "production_jobs", "episode_scripts", "artwork_assets",
];

const snap = buildSeedSnapshot(new Date());
const lines = ["-- Generated by scripts/export-seed-sql.ts – do not edit by hand.", "begin;"];
for (const table of ORDER) {
  const rows = snap[table] as unknown[];
  if (!rows.length) continue;
  const json = JSON.stringify(rows).replace(/'/g, "''");
  lines.push(`insert into public.${table} select * from jsonb_populate_recordset(null::public.${table}, '${json}'::jsonb);`);
}
lines.push("commit;");
const out = path.resolve("supabase/seed.sql");
fs.writeFileSync(out, lines.join("\n") + "\n");
console.log(`Wrote ${out}`);
