/**
 * Writes supabase/seed.sql from the same deterministic seed the local store uses.
 * Usage: npm run db:seed-sql  (then: supabase db reset, or psql -f supabase/seed.sql)
 */
import fs from "node:fs";
import path from "node:path";
import { buildSeedSnapshot } from "../src/lib/seed/build";
import { TABLE_NAMES } from "../src/lib/db/types";

// Insert order respects foreign keys.
const ORDER = [
  "users", "user_roles", "subscription_entitlements", "creator_profiles", "user_settings", "voice_profiles", "soundscapes",
  "series", "seasons", "audio_assets", "episodes", "scripts", "script_versions", "episode_productions", "story_bibles",
  "characters", "artwork_assets", "character_relationships", "locations", "narrative_events", "ai_conversations", "ai_tool_calls",
  "agent_configurations", "production_workflows", "ai_production_jobs", "production_costs", "ai_settings", "publishing_schedules",
  "editorial_reviews", "rights_declarations", "content_reports", "user_libraries", "series_follows", "creator_follows",
  "listening_progress", "listening_events", "notifications",
] as const;

// Columns stored as Postgres text[] / int[] rather than jsonb.
const ARRAY_COLUMNS: Record<string, Record<string, "text" | "int">> = {
  series: { tags: "text" },
  story_bibles: { rules: "text", themes: "text", established_facts: "text", unresolved_threads: "text", creator_preferences: "text" },
  narrative_events: { character_ids: "text" },
  production_workflows: { release_days: "int" },
};

function lit(v: unknown, table: string, col: string): string {
  if (v === null || v === undefined) return "null";
  const arr = ARRAY_COLUMNS[table]?.[col];
  if (arr && Array.isArray(v)) {
    return `array[${v.map((x) => (arr === "int" ? String(Number(x)) : `'${String(x).replace(/'/g, "''")}'`)).join(",")}]::${arr}[]`;
  }
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "true" : "false";
  if (typeof v === "object") return `'${JSON.stringify(v).replace(/'/g, "''")}'::jsonb`;
  return `'${String(v).replace(/'/g, "''")}'`;
}

export function seedSql(now = new Date()): string {
  const snap = buildSeedSnapshot(now);
  if (ORDER.length !== TABLE_NAMES.length) throw new Error("ORDER is missing tables");
  const out: string[] = ["-- Generated by scripts/export-seed-sql.ts. Do not edit by hand.", "begin;", "set constraints all deferred;"];
  for (const table of ORDER) {
    for (const row of snap[table] as unknown as Record<string, unknown>[]) {
      const cols = Object.keys(row);
      out.push(`insert into ${table} (${cols.join(", ")}) values (${cols.map((c) => lit(row[c], table, c)).join(", ")});`);
    }
  }
  out.push("commit;");
  return out.join("\n") + "\n";
}

if (process.argv[1] && process.argv[1].endsWith("export-seed-sql.ts")) {
  const file = path.resolve(__dirname, "../supabase/seed.sql");
  fs.writeFileSync(file, seedSql());
  console.log(`Wrote ${file}`);
}
